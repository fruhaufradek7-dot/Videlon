/// Důvod, proč nelze video přehrát, podle chybových kódů
/// `youpipe/stream_extractor` (docs/streaming.md).
class VideoUnavailable implements Exception {
  VideoUnavailable(this.code, this.message);

  /// `AGE_RESTRICTED`, `GEO_RESTRICTED`, `UNAVAILABLE`, `RECAPTCHA`,
  /// `BOT_CHECK`, `NO_STREAMS` nebo `EXTRACTION_FAILED`.
  final String code;
  final String message;

  String get friendly => switch (code) {
    'AGE_RESTRICTED' => 'Toto video je věkově omezené',
    'GEO_RESTRICTED' => 'Toto video není ve vaší zemi dostupné',
    'UNAVAILABLE' => 'Toto video není dostupné',
    'RECAPTCHA' => 'YouTube omezuje požadavky z tohoto zařízení. Zkuste to později znovu',
    'BOT_CHECK' => 'YouTube potřebuje ověřit, že nejste robot. Zkuste to za chvíli znovu',
    'NO_STREAMS' => 'Pro toto video není dostupný žádný přehratelný stream',
    _ => 'Toto video se nepodařilo načíst',
  };

  @override
  String toString() => 'VideoUnavailable($code): $message';
}

class CaptionTrack {
  const CaptionTrack({required this.url, required this.languageCode, required this.name, required this.autoGenerated});

  final String url;
  final String languageCode;
  final String name;
  final bool autoGenerated;
}

class Chapter {
  const Chapter(this.title, this.start, this.thumbnail);

  final String title;
  final Duration start;
  final String? thumbnail;
}

/// Úroveň storyboardu: sady obrázků s [framesPerPageX] × [framesPerPageY]
/// snímky, přičemž každý snímek odpovídá hodnotě [durationPerFrame].
class Storyboard {
  const Storyboard({
    required this.urls,
    required this.frameWidth,
    required this.frameHeight,
    required this.totalCount,
    required this.durationPerFrame,
    required this.framesPerPageX,
    required this.framesPerPageY,
  });

  final List<String> urls;
  final int frameWidth;
  final int frameHeight;
  final int totalCount;
  final Duration durationPerFrame;
  final int framesPerPageX;
  final int framesPerPageY;
}

/// Veškeré informace o jednom videu získané pomocí NewPipeExtractor:
/// metadata a všechny dostupné možnosti přehrávání.
class VideoInfo {
  VideoInfo._(this.raw, {this.manifestPath});

  /// Informace o staženém videu z knihovny (bez připojení k síti).
  VideoInfo.offline({
    required String videoId,
    required String title,
    String? channelName,
    String? channelId,
    String? channelAvatar,
  }) : this._({
         'videoId': videoId,
         'title': title,
         'channelName': channelName,
         'channelId': channelId,
         'channelAvatar': channelAvatar,
       });

  final Map<Object?, Object?> raw;

  /// Cesta k místnímu souboru s manifestem DASH, pokud existuje.
  final String? manifestPath;

  String get videoId => raw['videoId'] as String;
  String get title => raw['title'] as String? ?? '';
  String? get channelId => raw['channelId'] as String?;
  String get channelName => raw['channelName'] as String? ?? '';
  String? get channelAvatar => raw['channelAvatar'] as String?;
  int get subscriberCount => (raw['subscriberCount'] as num?)?.toInt() ?? -1;
  int get viewCount => (raw['viewCount'] as num?)?.toInt() ?? -1;
  int get likeCount => (raw['likeCount'] as num?)?.toInt() ?? -1;
  String? get uploadDate => raw['uploadDate'] as String?;
  String get description => raw['description'] as String? ?? '';
  Duration get duration => Duration(seconds: (raw['durationSeconds'] as num?)?.toInt() ?? 0);
  bool get isLive => raw['isLive'] == true;
  bool get isShort => raw['isShort'] == true;
  String? get hlsUrl => raw['hlsUrl'] as String?;
  String? get muxedUrl => raw['muxedUrl'] as String?;
  int? get muxedHeight => (raw['muxedHeight'] as num?)?.toInt();
  List<int> get dashHeights => (raw['dashHeights'] as List?)?.cast<int>() ?? const [];
  String? get dashCodec => raw['dashCodec'] as String?;

  /// Hlavička User-Agent potřebná pro adresy jednotlivých zdrojů:
  /// adresy jsou svázané s klientem InnerTube, který je vytvořil.
  /// Streamy DASH a muxed mohou pocházet od různých klientů.
  String get dashUserAgent => raw['dashUserAgent'] as String? ?? '';
  String get muxedUserAgent => raw['muxedUserAgent'] as String? ?? '';
  String get hlsUserAgent => raw['hlsUserAgent'] as String? ?? '';

  /// Dostupné možnosti stažení: (rozlišení, celková velikost v bajtech),
  /// seřazené od nejnižšího rozlišení.
  List<(int, int)> get downloadOptions => [
    for (final o in (raw['downloadOptions'] as List? ?? const []).cast<Map>())
      ((o['height'] as num).toInt(), (o['size'] as num? ?? 0).toInt()),
  ];

  List<CaptionTrack> get captions => [
    for (final c in (raw['captions'] as List? ?? const []).cast<Map>())
      CaptionTrack(
        url: c['url'] as String,
        languageCode: c['languageCode'] as String? ?? '',
        name: c['name'] as String? ?? '',
        autoGenerated: c['autoGenerated'] == true,
      ),
  ];

  List<Chapter> get chapters => [
    for (final c in (raw['chapters'] as List? ?? const []).cast<Map>())
      Chapter(
        c['title'] as String? ?? '',
        Duration(seconds: (c['startSeconds'] as num?)?.toInt() ?? 0),
        c['thumbnail'] as String?,
      ),
  ];

  List<Storyboard> get storyboards => [
    for (final s in (raw['storyboards'] as List? ?? const []).cast<Map>())
      Storyboard(
        urls: (s['urls'] as List).cast<String>(),
        frameWidth: (s['frameWidth'] as num).toInt(),
        frameHeight: (s['frameHeight'] as num).toInt(),
        totalCount: (s['totalCount'] as num).toInt(),
        durationPerFrame: Duration(milliseconds: (s['durationPerFrameMs'] as num).toInt()),
        framesPerPageX: (s['framesPerPageX'] as num).toInt(),
        framesPerPageY: (s['framesPerPageY'] as num).toInt(),
      ),
  ];

  /// Čas vypršení platnosti adres streamů podle parametru `expire`,
  /// případně za jednu hodinu, pokud tento údaj není k dispozici.
  DateTime get expires {
    final url = muxedUrl ?? hlsUrl ?? '';
    final m = RegExp(r'[?&/]expire[=/](\d+)').firstMatch(url);
    final s = m == null ? null : int.tryParse(m.group(1)!);
    return s == null ? DateTime.now().add(const Duration(hours: 1)) : DateTime.fromMillisecondsSinceEpoch(s * 1000);
  }
}

/// Volá `youpipe/stream_extractor` a ukládá výsledky do mezipaměti
/// až do deseti minut před vypršením platnosti adres.
class VideoInfoService {
  VideoInfoService({this.hl = 'en', this.gl = 'US'});

  static const _channel = MethodChannel('youpipe/stream_extractor');

  String hl;
  String gl;

  final _cache = <String, VideoInfo>{};
  final _pending = <String, Future<VideoInfo>>{};

  Future<VideoInfo> get(String videoId, {int maxHeight = 1080, bool forceRefresh = false}) {
    final key = '$videoId@$maxHeight';
    final cached = _cache[key];
    if (!forceRefresh &&
        cached != null &&
        DateTime.now().isBefore(cached.expires.subtract(const Duration(minutes: 10)))) {
      return Future.value(cached);
    }
    // Callback nesmí vrátit právě odstraňovaný Future:
    // metoda whenComplete by pak čekala sama na sebe.
    return _pending[key] ??= _fetch(videoId, maxHeight, key).whenComplete(() {
      _pending.remove(key);
    });
  }

  Future<VideoInfo> _fetch(String videoId, int maxHeight, String key) async {
    Map<Object?, Object?>? raw;
    for (var attempt = 0; raw == null; attempt++) {
      try {
        raw = await _channel.invokeMapMethod<Object?, Object?>('getVideoInfo', {
          'videoId': videoId,
          'hl': hl,
          'gl': gl,
          'maxHeight': maxHeight,
        });
      } on PlatformException catch (e) {
        // YouTube občas pošle NewPipe místo JSON stránky HTML;
        // druhý pokus obvykle pomůže.
        if (e.code != 'EXTRACTION_FAILED' || attempt > 0) {
          throw VideoUnavailable(e.code, e.message ?? e.code);
        }
        await Future<void>.delayed(const Duration(seconds: 1));
      }
    }
    String? manifestPath;
    final mpd = raw['dashMpd'] as String?;
    if (mpd != null) {
      final dir = Directory('${(await getTemporaryDirectory()).path}/video');
      await dir.create(recursive: true);
      manifestPath = '${dir.path}/${videoId}_$maxHeight.mpd';
      await File(manifestPath).writeAsString(mpd);
    }
    final info = VideoInfo._(raw, manifestPath: manifestPath);
    _cache[key] = info;
    if (_cache.length > 50) _cache.remove(_cache.keys.first);
    return info;
  }

  void invalidate(String videoId) => _cache.removeWhere((k, _) => k.startsWith('$videoId@'));
}
